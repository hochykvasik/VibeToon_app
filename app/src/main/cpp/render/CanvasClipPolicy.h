namespace vt {
// Монтажный стол виден только в редакторе; захват и экспорт ограничены кадром.
constexpr bool clipSceneToCanvas(bool exportMode) { return exportMode; }
// Смещение уровня mip при выборке слоёв. Трилинейная фильтрация при уменьшении (холст 1080 -> 720p)
// подмешивает уровень вдвое меньшего разрешения - видео выглядит «мыльным». В экспорте сдвигаем
// выбор к более чёткому уровню на полступени; в редакторе оставляем 0 (без мерцания при зуме).
constexpr float exportLodBias(bool exportMode) { return exportMode ? -0.5f : 0.f; }
}
