package com.vibetoon.domain.input

/**
 * Спринт 49: экранная клавиатура больше не сжимает редактор. Раньше корень редактора отступал на высоту клавиатуры
 * (`safeDrawing` включает клавиатуру): холст, таймлайн и панели схлопывались в оставшуюся полосу и перестраивались при
 * каждом открытии/закрытии. Теперь корень и холст не меняются, а над клавиатурой подстраиваются только панели с полями:
 * правая панель (инспектор) - отступом снизу, нижняя панель (таймлайн) - сдвигом поверх холста, пока в ней фокус ввода.
 */
object KeyboardLift {
    /**
     * Сдвиг вверх панели с полем ввода: клавиатура высотой [imeBottom] px от низа окна, низ панели на [gapBelow] px
     * выше низа окна. Без фокуса в панели (или без клавиатуры) - 0: панель стоит на месте.
     */
    fun lift(focused: Boolean, imeBottom: Int, gapBelow: Int): Int =
        if (!focused || imeBottom <= 0) 0 else (imeBottom - gapBelow.coerceAtLeast(0)).coerceAtLeast(0)

    /** Отступ снизу у панели во всю высоту (её низ на [gapBelow] px выше низа окна): поля не уходят под клавиатуру. */
    fun panelInset(imeBottom: Int, gapBelow: Int): Int = (imeBottom - gapBelow.coerceAtLeast(0)).coerceAtLeast(0)

}
