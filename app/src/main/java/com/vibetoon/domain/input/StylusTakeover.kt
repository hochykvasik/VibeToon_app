package com.vibetoon.domain.input

/**
 * Спринт 58: перо перехватывает жест у ладони. Чистые функции - Sprint58Test.
 *
 * Раньше ладонь, положенная на экран раньше пера, начинала жест сама (штрих пальцем, сдвиг камеры или «защита от
 * ладони», которая гасит касания до отпускания всех пальцев). Перо внутри такого жеста игнорировалось, пока ладонь не
 * поднята, а при выключенной «Определение касаний» ладонь и перо вместе давали щипок камеры. Теперь касание пера
 * внутри жеста, начатого пальцем, при активной кисти или ластике забирает жест: штрих/сдвиг ладони отменяется, перо
 * рисует, ладонь до конца жеста не участвует. Повторные касания пера при лежащей ладони - новые штрихи.
 */
object StylusTakeover {
    /**
     * Забрать ли жест пером. [gestureByTouch] - жест начат пальцем (ладонью); [penPressed]/[penWasPressed] - перо в
     * этом событии касается и касалось ли в прошлом (берётся только новое касание); [paintTool] - кисть или ластик.
     */
    fun shouldTakeOver(gestureByTouch: Boolean, penPressed: Boolean, penWasPressed: Boolean, paintTool: Boolean): Boolean =
        gestureByTouch && paintTool && penPressed && !penWasPressed
}
