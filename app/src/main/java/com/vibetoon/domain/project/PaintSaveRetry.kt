package com.vibetoon.domain.project

/**
 * Спринт 41: когда показывать «Не удалось сохранить рисунок; проект не сохранён».
 *
 * Причина ложного баннера на новом устройстве: автосохранение запускалось через 250 мс после ON_PAUSE, когда
 * поверхность GL уже снята - пиксели слоя прочитать нельзя (контекст не текущий), и сохранение «проваливалось», хотя
 * с рисунком всё в порядке; после возврата следующее автосохранение проходило и баннер исчезал. Теперь пиксели
 * изменённых слоёв читаются ДО паузы поверхности, а временные отказы (поверхность на паузе, текстура ещё грузится,
 * нет GL-вида) повторяются молча. Ошибка показывается только при постоянном отказе (нет файла слоя, не совпал размер,
 * запись на диск не удалась) или после нескольких временных отказов подряд на переднем плане.
 */
object PaintSaveRetry {
    const val MAX_TRANSIENT = 3

    /** Показывать ли ошибку после [failures] отказов подряд. */
    fun report(failures: Int, transient: Boolean, background: Boolean): Boolean = when {
        background -> false
        !transient -> true
        else -> failures >= MAX_TRANSIENT
    }

    /** Пауза перед повтором (мс): 0,8 / 1,6 / 2,4 с ..., не больше 5 с. */
    fun delayMs(failures: Int): Long = (800L * failures.coerceAtLeast(1)).coerceAtMost(5000L)
}
