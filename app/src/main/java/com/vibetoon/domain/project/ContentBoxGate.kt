package com.vibetoon.domain.project

/**
 * Спринт 60: причина вечного «Приложение VibeToon не отвечает» после «Создать символ → Слои как кадры».
 *
 * Рамка выделения слоя строится по его содержимому (границы альфы). Для экземпляра символа своей текстуры нет -
 * границы берутся из готовых форм. Сразу после создания символа форм ещё нет, и расчёт возвращал «данных нет»
 * БЕЗ кэша и без единой приостановки корутины. Цепочка была замкнутой:
 *
 *   рамка выделения -> границ нет в кэше -> запуск расчёта (viewModelScope = Main.immediate, выполняется сразу)
 *   -> форм нет, «данных нет» без кэша -> перерисовать рамку выделения -> границ нет в кэше -> запуск расчёта ...
 *
 * Вложенные запуски Main.immediate не переполняют стек, а встают в очередь цикла событий того же вызова, поэтому
 * главный поток крутился бесконечно, а формы символа (единственный выход из цикла) так и не снимались - им нужен
 * тот же главный поток. Окно «Создать символ» оставалось на экране, через несколько секунд система показывала ANR.
 *
 * Правило: для одного слоя одновременно идёт не больше одного расчёта; расчёт, не давший результата, «паркует» слой -
 * следующий запускается только после того, как содержимое слоя или формы его символа изменились ([forget]).
 * Рамку выделения стоит перерисовывать только после расчёта, результат которого попал в кэш.
 * Только главный поток. Чистый класс - unit-тест.
 */
class ContentBoxGate {
    private val inFlight = HashSet<Int>()
    private val parked = HashSet<Int>()

    /** Можно ли запустить расчёт границ слоя [id]: не идёт уже и не ждёт новых данных. true - расчёт помечен как идущий. */
    fun begin(id: Int): Boolean {
        if (id in inFlight || id in parked) return false
        inFlight += id
        return true
    }

    /**
     * Расчёт слоя [id] закончился; [cached] - результат лёг в кэш. Возвращает, нужно ли перерисовать рамку выделения
     * (только при новом результате - иначе перерисовка снова запросила бы расчёт).
     */
    fun end(id: Int, cached: Boolean): Boolean {
        inFlight -= id
        if (!cached) parked += id
        return cached
    }

    /** Содержимое слоя или формы его символа изменились: расчёт снова разрешён. */
    fun forget(id: Int) { parked -= id }

    /** Другой проект: всё заново. */
    fun clear() { inFlight.clear(); parked.clear() }

    fun isBusy(id: Int): Boolean = id in inFlight
    fun isParked(id: Int): Boolean = id in parked
}
