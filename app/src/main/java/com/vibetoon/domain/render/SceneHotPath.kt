package com.vibetoon.domain.render

import com.vibetoon.domain.anim.WarpMath

/**
 * Спринт 43: правила «горячего пути» Play/скраббинга. Сцена пересобирается на каждом кадре, поэтому всё, что не
 * меняется от кадра к кадру, не должно пересчитываться, а в списки узлов не должны попадать служебные id.
 */
object SceneHotPath {
    /**
     * Узел сцены (слой PSD, медиа-слой, группа, кость, призрак кальки): неотрицательный id ниже диапазона точек Warp.
     * Вершины сеток, точки Warp/Perspective, параметры Turbulent, пины и положения на пути - не узлы: их значения
     * читают свои деформеры, а не список трансформаций слоёв.
     */
    fun isNodeId(id: Int): Boolean = id >= 0 && id < WarpMath.ID_BASE
}
