package com.vibetoon.domain.perf

/**
 * Спринт 31: правила декодирования кадров видео-слоёв при воспроизведении и перемотке.
 * Спринт 46: кадры берёт последовательный декодер (дешевле поиска на каждый кадр), поэтому при Play размер кадра
 * больше прежнего: 960 px для одного видео, 720 px для 2-3, 480 px для 4 и больше.
 */
object VideoDecodePolicy {
    /** Потоков декодирования видео: 1 на 4 ядра, не больше 2 (у каждого слоя свой декодер, слой - один поток). */
    fun threads(cpus: Int): Int = (cpus / 4).coerceIn(1, 2)

    /**
     * Длинная сторона кадра источника: при воспроизведении 640 px (один слой) или 480 px (несколько видео сразу -
     * декод каждого быстрее, кадры не отстают), на паузе 1280 px для чёткой картинки.
     */
    fun maxSide(playing: Boolean, videoLayers: Int): Int = when {
        !playing -> 1280
        videoLayers > 3 -> 480
        videoLayers > 1 -> 720
        else -> 960
    }

    /**
     * Спринт 46: сколько видео-слоёв сразу держат свой последовательный декодер (MediaCodec). Аппаратных декодеров на
     * устройстве немного (обычно 8-16 на всё приложение и экспорт), поэтому остальные слои идут прежним путём
     * (MediaMetadataRetriever) - кадры показываются, просто медленнее; ни один слой не отключается.
     */
    const val MAX_STREAMS = 6

    /** Можно ли открыть ещё один декодер, если уже открыто [open]. */
    fun canOpenStream(open: Int): Boolean = open < MAX_STREAMS
}
